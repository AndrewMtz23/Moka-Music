class I18n:
    def __init__(self, language: LanguageCode = DEFAULT_LANGUAGE) -> None:
        self.language = normalize_language(language)

    def set_language(self, language: LanguageCode) -> None:
        self.language = normalize_language(language)

    def t(self, key: str, **kwargs: Any) -> str:
        text = TRANSLATIONS.get(self.language, TRANSLATIONS[DEFAULT_LANGUAGE]).get(key)
        if text is None:
            text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
        return text.format(**kwargs) if kwargs else text


def normalize_language(language: LanguageCode | None) -> LanguageCode:
    if language in SUPPORTED_LANGUAGES:
        return language
    return DEFAULT_LANGUAGE
